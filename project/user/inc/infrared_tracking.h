#ifndef _infrared_tracking_h_
#define _infrared_tracking_h_

#include "zf_common_typedef.h"

#define IR_CHANNEL_NUM              5

// 红外模块数字输出电平定义 (典型红外模块: 黑线=低电平, 白底=高电平)
#define IR_LINE_DETECT              0       // 检测到黑线
#define IR_NO_LINE                  1       // 未检测到黑线(白底)

//-------------------------------------------------------------------------------------------------------------------
// 寻迹线状态枚举
// 用于描述当前小车相对黑线的位置
//-------------------------------------------------------------------------------------------------------------------
typedef enum
{
    LINE_LOST       = -3,   // 全线丢失 (5路全白, 可能冲出赛道)
    LINE_FAR_LEFT   = -2,   // 线在较左位置
    LINE_LEFT       = -1,   // 线在左侧
    LINE_CENTER     =  0,   // 线在中间 (理想跟踪状态)
    LINE_RIGHT      =  1,   // 线在右侧
    LINE_FAR_RIGHT  =  2,   // 线在较右位置
    LINE_CROSS      =  3,   // 十字交叉 (5路全黑)
} line_state_enum;


//-------------------------------------------------------------------------------------------------------------------
// 红外传感器数据结构体
// 包含原始读数、加权位置、有效传感器数量和线状态
//-------------------------------------------------------------------------------------------------------------------
typedef struct
{
    uint8           raw[IR_CHANNEL_NUM];    // 原始读数: 0=检测到线, 1=未检测到线
    int8            position;               // 加权位置: -2 ~ +2 (连续值)
    uint8           active_count;           // 检测到线的传感器数量
    line_state_enum state;                  // 线状态分类
} ir_sensor_data_t;


//-------------------------------------------------------------------------------------------------------------------
// 函数声明
//-------------------------------------------------------------------------------------------------------------------
void ir_tracking_init           (void);
void ir_tracking_read           (ir_sensor_data_t *data);
void ir_tracking_compact_print  (const ir_sensor_data_t *data);
void ir_tracking_detail_print   (const ir_sensor_data_t *data);

#endif
